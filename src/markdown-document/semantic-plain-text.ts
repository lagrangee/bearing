const SEMANTIC_MARKUP_PATTERNS = [
  /`/u,
  /!?(?:\[[^\]\n]*\])\([^\n)]*\)/u,
  /!?(?:\[[^\]\n]+\])\[[^\]\n]*\]/u,
  /(?:^|\n)[ \t]{0,3}\[[^\]\n]+\]:[ \t]*\S/u,
  /\*\*\*(?![\s*])[^*\n]*\S\*\*\*/u,
  /(?<![\p{L}\p{N}_])___(?![\s_])[^_\n]*\S___(?![\p{L}\p{N}_])/u,
  /\*\*[^*\n]+\*\*/u,
  /(?<![\p{L}\p{N}_])__(?![\s_])[^_\n]*\S__(?![\p{L}\p{N}_])/u,
  /~~[^~\n]+~~/u,
  /\*(?![\s*])[^*\n]*\S\*/u,
  /(?<![\p{L}\p{N}_])_(?![\s_])[^_\n]*\S_(?![\p{L}\p{N}_])/u,
  /<!--/u,
  /<[!?]/u,
  /<\?[^>\n]*\?>/u,
  /<![^>\n]*>/u,
  /<\/?[A-Za-z][^>\n]*>/u,
  /(?:^|\n)[ \t]{0,3}<\/?[A-Za-z][A-Za-z0-9-]*(?=[\s/]|$)/u,
  /(?:^|\n)[ \t]*(?:#{1,6}[ \t]+|>|(?:[-+*]|\d+[.)])[ \t]+)/u,
  /(?:^|\n)[ \t]{0,3}(?:#{1,6}|>|[-+*]|\d+[.)])[ \t]*(?=\n|$)/u,
  /(?:^|\n)[ \t]{0,3}>[ \t]?\S/u,
  /(?:^|\n)[ \t]*~~~+/u,
  /(?:^|\n)[ \t]{0,3}(?:(?:\*[ \t]*){3,}|(?:-[ \t]*){3,}|(?:_[ \t]*){3,}|={3,})[ \t]*(?=\n|$)/u,
  /(?:^|\n)[ \t]{0,3}(?:=+|-+)[ \t]*(?=\n|$)/u,
  /(?:^|\n)[ \t]*\|?[ \t]*:?-+:?[ \t]*(?:\|[ \t]*:?-+:?[ \t]*)+\|?[ \t]*(?=\n|$)/u,
  /(?:^|\n)[ \t]*\|[ \t]*:?-+:?[ \t]*\|[ \t]*(?=\n|$)/u,
  /(?:^|\n)(?: {4,}|\t+)\S/u,
  /[ \t]{2,}(?:\r\n|\n|\r)/u,
  /\\(?:\r\n|\n|\r)/u,
] as const;

export const isSemanticPlainText = (source: string): boolean => {
  const normalized = source.replaceAll("\r\n", "\n").replaceAll("\r", "\n");
  const softWrapped = normalized.replace(/(?<!\n)\n(?!\n)/gu, " ");
  return [normalized, softWrapped].every((value) =>
    SEMANTIC_MARKUP_PATTERNS.every((pattern) => !pattern.test(value)),
  );
};
